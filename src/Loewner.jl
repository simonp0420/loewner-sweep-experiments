"""
    SweepOptions(Δf, q1, q2, adaptive, tol, l, p, memory, use_D, data_partition, parallel, nthreads)
Options struct for performing a fast sweep.

A keyword constructor is also available. All fields have default values.

## Fields
$(DSE.TYPEDFIELDS)
"""
@kwdef struct SweepOptions
    "Frequency increment (defaults to `1e-8 GHz`) for pseudo error calculation"
    Δf::Float64 = 1e-8

    "Exponent (defaults to 8) used for determining order of first reduced model"
    q1::Int = 8

    "Exponent (defaults to 12) used for determining order of second reduced model"
    q2::Int = 12

    "`true` (default) for fully adaptive fast sweep, otherwise semiadaptive"
    adaptive::Bool = true

    "Tolerance for convergence of sweep (defaults to 0.001)"
    tol::Float64 = 10^(-60 / 20)

    "Electrical length (defaults to 0.02 [m]) used to determine initial number of frequencies in semiadaptive fast sweep"
    l::Float64 = 0.02

    "Number of ports (defaults to 2) in the circuit being modeled."
    p::Int = 2

    "Termination criterion: no. of consecutive times (defaults to 3) that `tol` must exceed actual error at a new frequency"
    memory::Int = 3

    "If `true` (default) then use a regularizing (all ones) matrix `D`"
    use_D::Bool = false

    "If `true` (default) then use parity for data partitioning, otherwise use sign of the complex frequency imaginary part."
    data_partition::Bool = true

    "If `true`, use threading to calculate pseudo errors (default value is `false`)"
    parallel::Bool = false

    "Number of tasks to spawn if `parallel` is `true`"
    nthreads::Int = Threads.nthreads()

    "If true, use random `Wa` and `Wb` matrices in the second Loewner model"
    random::Bool = false
end

"""
    LoewnerStateModel{T}(E, A, B, C, f₀, H₀)
Stores the state matrices, evaluated frequencies, and corresponding scattering matrices for a Loewner state model.

## Fields
$(DSE.TYPEDFIELDS)
"""
struct LoewnerStateModel{T}
    "State matrix"
    E::Matrix{Complex{T}}

    "State matrix"
    A::Matrix{Complex{T}}

    "State matrix"
    B::Matrix{Complex{T}}

    "State matrix"
    C::Matrix{Complex{T}}

    "Frequencies at which the model has been evaluated using the solver"
    f₀::Vector{T}

    """
    Scattering matrices generated by the solver at frequencies in f₀.
    These may have been modified by subtracting the `D` matrix from each.
    """
    H₀::Vector{Matrix{Complex{T}}}
end

"""
    (interp::LoewnerStateModel)(f::Real)
    (interp::LoewnerStateModel)(f::AbstractVector)

Interpolate a Loewner model at frequency `f`.  See Eq. (3) of
reference [1] from the `$(@__MODULE__)` module documentation.
"""
function (interp::LoewnerStateModel)(f::Real)
    s = im * 2π * f
    return interp.C * ((s * interp.E - interp.A) \ interp.B)
end

function (interp::LoewnerStateModel)(f::AbstractVector)
    return map(fᵢ -> interp(fᵢ), f)
end

"""
    loewner_partition_posneg(f, S) -> (sa, sb, Ha, Hb)

Expand a set of frequency-transfer function pairs to include negative
frequencies using the complex-symmetric property of linear, time-invariant systems.
Partition these on output according to the sign of the frequency.

## Input Arguments
- `f`: A positive (scalar) frequency or collection of positive frequencies.
- `S`: A collection of scalar or matrix-valued transfer functions of the same length as `f`.

## Return Values (all of length equal to `length(f)`):
- `sa`: Vector of complex frequencies with negative imaginary parts.
- `sb`: Vector of complex frequencies with positive imaginary parts.
- `Sa`: Vector of complex transfer function matrices corresponding to frequencies in `sa`.
- `Sb`: Vector of complex transfer function matrices corresponding to frequencies in `sb`.
"""
function loewner_partition_posneg(f, S)
    n = length(f)
    n == length(S) || throw(ArgumentError("f and S must have same length"))

    any(iszero, f) && throw(ArgumentError("f contains 0. Use fmin > 0 to avoid s == conj(s)."))

    sa = Vector{ComplexF64}(undef, n)
    sb = Vector{ComplexF64}(undef, n)
    Ha = Vector{Matrix{ComplexF64}}(undef, n)
    Hb = Vector{Matrix{ComplexF64}}(undef, n)

    for k in 1:n
        s = 2π * im * f[k]
        sb[k] = s
        Hb[k] = Matrix{ComplexF64}(S[k])
        sa[k] = conj(s)
        Ha[k] = conj(S[k])
    end

    return sa, sb, Ha, Hb
end

"""
    loewner_partition_evenodd(f, S) -> (sa, sb, Ha, Hb)

Expand a set of frequency-transfer function pairs to include negative
frequencies using the complex-symmetric property of linear, time-invariant systems.
Partition these on output according to the parity of the frequency index.

## Input Arguments
- `f`: A positive (scalar) frequency or collection of positive frequencies.
- `S`: A collection of scalar or matrix-valued transfer functions of the same length as `f`.

## Return Values (all of length equal to `length(f)`):
- `sa`: Vector of complex frequencies with even frequency indices.
- `sb`: Vector of complex frequencies with odd frequency indices.
- `Sa`: Vector of complex transfer function matrices corresponding to frequencies in `sa`.
- `Sb`: Vector of complex transfer function matrices corresponding to frequencies in `sb`.
"""
function loewner_partition_evenodd(f, S)
    n = length(f)
    n == length(S) || throw(ArgumentError("f and S must have same length"))
    any(iszero, f) && throw(ArgumentError("f contains 0. Use fmin > 0 to avoid s == conj(s)."))

    sa = Vector{ComplexF64}(undef, n)
    sb = Vector{ComplexF64}(undef, n)
    Ha = Vector{Matrix{ComplexF64}}(undef, n)
    Hb = Vector{Matrix{ComplexF64}}(undef, n)

    n_even = iseven(n) ? n : n - 1

    for i in 1:2:n_even
        si = 2π * im * f[i]
        k = (i + 1) ÷ 2
        sb[2*k-1] = si
        sb[2*k]   = conj(si)
        Hb[2*k-1] = S[i]
        Hb[2*k]   = conj(S[i])
    end
    for i in 2:2:n_even
        si = 2π * im * f[i]
        k = i ÷ 2
        sa[2*k-1] = si
        sa[2*k]   = conj(si)
        Ha[2*k-1] = S[i]
        Ha[2*k]   = conj(S[i])
    end

    # último punto si n es impar: positivo-negativo
    if isodd(n)
        sn = 2π * im * f[n]
        sb[n] = sn
        Hb[n] = S[n]
        sa[n] = conj(sn)
        Ha[n] = conj(S[n])
    end

    return sa, sb, Ha, Hb
end

"""
    loewner_data_partition(f, S, flag) -> (sa, sb, Ha, Hb)

Expand a set of frequency-transfer function pairs to include negative
frequencies using the complex-symmetric property of linear, time-invariant systems.
Partition these on output according to either
- the parity of the frequency index if `flag == true`, or
- the sign of the frequency if `flag == false`.
See `loewner_partition_evenodd` and `loewner_partition_posneg` for details on the
returned values in these two cases.
"""
function loewner_data_partition(f, S, flag)
    if flag == true
        return loewner_partition_evenodd(f, S)
    else
        return loewner_partition_posneg(f, S)
    end
end

"""
    loewner_mfti(Ha, Hb, sa, sb) -> (L, σL)
Construct a Loewner Matrix (LM) and shifted LM using matrix format tangential interpolation.

## Input Arguments
- `Ha`, `Hb`: Collections of of `n` network transfer function matrices corresponding to the frequencies in
- `sa`, `sb`: Abstract vectors each of the same type and length `n` containing the complex frequencies.
  `sa` and `sb`, resp.  Each element of `Ha` and `Hb` is a square complex matrix of order `p` where `p` is
  the number of ports in the network.
## Return Values
- `L`, `σL`: The LM and shifted LM.  Each is a square matrix of order `n * p`.  The computations
  follow Eq. (9) of reference [1] from the `$(@__MODULE__)` module documentation.
"""
function loewner_mfti(Ha, Hb, sa::AbstractVector{Complex{T}}, sb::AbstractVector{Complex{T}}) where T
    p = size(Ha[1], 1)
    n = length(sa)
    L = Matrix{Complex{T}}(undef, n * p, n * p)
    σL = Matrix{Complex{T}}(undef, n * p, n * p)
    for i in eachindex(Hb)
        rows = (i-1)*p+1:i*p
        Hbi = Hb[i]
        sbi = sb[i]
        for j in eachindex(Ha)
            cols = (j-1)*p+1:j*p
            Haj = Ha[j]
            saj = sa[j]
            L[rows, cols] .= (Haj - Hbi) / (saj - sbi)
            σL[rows, cols] .= (saj * Haj - sbi * Hbi) / (saj - sbi)
        end
    end
    return L, σL
end

"""
    vw_mfti(Ha, Hb) -> (V, W)
Compute left and right data matrices used in matrix format tangential interpolation.

## Input Arguments
- `Ha`, `Hb`: Collections of length `n` whose elements are square matrices of order `p`.  The matrices
  are transfer functions of `p`-port linear, time-invariant networks.

## Return Values
- `V`: The left data matrix, a `Matrix{ComplexF64}` of size `(n * p, p)`.
- `W`: The right data matrix, a `Matrix{ComplexF64}` of size `(p, n * p)`.

See the unnumbered equations between Eq. (7) and (8) of reference [1] from the `$(@__MODULE__)`
module documentation.
"""
function vw_mfti(Ha, Hb)
    n = length(Ha)
    p = size(Ha[1], 1)
    W = Matrix{ComplexF64}(undef, p, n * p)
    V = Matrix{ComplexF64}(undef, n * p, p)
    for j in 1:n
        cols = (j-1)*p+1:j*p
        rows = (j-1)*p+1:j*p
        W[:, cols] .= Ha[j]
        V[rows, :] .= Hb[j]
    end
    return V, W
end

"""
    semi_adaptive_n(options, fmax) -> n₀::Int
Estimate initial number of full-wave simulations needed for semi-adaptive sweep.
Uses Eq. (13) of reference [1] found in the `$(@__MODULE__)` module documentation.

# Input arguments
- `options`: A `struct` or `NamedTuple` having at least the following fields:
  * `l`: The length in meters of the structure being analyzed.
  * `p`: The number of ports of the electrical network being modeled.
- `fmax`: The maximum frequency in Hz of the desired frequency sweep.
## Return Value
- `n₀`: An estimate for the number of frequency samples needed for accurate interpolation.
"""
semi_adaptive_n(options, fmax) = ceil(Int, 15 * options.l * fmax / (options.p * 3E8))

"""
    semi_adaptive_freqs(fmin, fmax, n₀) -> freqs::Vector{Float64}
Compute a vector of `n₀` nonuniformly spaced frequencies between `fmin` and `fmax`
(inclusive) according to Eq. (13) of reference [1] found in the `$(@__MODULE__)` module
documentation.
"""
semi_adaptive_freqs(fmin, fmax, n₀) = 2 * fmax .+ fmin .- 10.0 .^ (range(log10(2 * fmax), log10(fmax + fmin), n₀))

"""
    loewner_order(σ::AbstractVector{<:Real}, q::Int=8) -> r::Int
Determine the reduced model order r of the LM formulation.

## Input Arguments
- `σ`: Vector of nonnegative singular values of the matrix pencil xL - σL, sorted into decreasing order.
- `q`: Parameter used to determine how many singular values to retain in the reduced order model. Must
  satisfy `6 ≤ q ≤ 12`.

## Return Value
- `r`: The order of the reduced-order system, computed using Eq. (19)
  of reference [1] found in the `$(@__MODULE__)` module documentation.
"""
function loewner_order(σ::AbstractVector, q::Int=8)
    6 <= q <= 12 || throw(ArgumentError("loewner_order: q must satisfy 6 ≤ q ≤ 12"))
    total = sum(σ)
    total < eps() && return 1
    threshold = total * (1 - 10.0^(-q))
    accum = zero(eltype(σ))
    for (r, σv) in enumerate(σ)
        accum += σv
        accum >= threshold && return r
    end
    return length(σ)
end

"""
    svd_matrix_pencil(x, L, σL) -> svd::LinearAlgebra.SVD
Compute the singular value decomposition of `x * L - σL`.
"""
@inline function svd_matrix_pencil(x, L, σL)
    return svd(x * L - σL)
end

"""
    loewner_reduce(L, σL, B, C, F, r)
Compute matrices defining the reduced-order Loewner model of the Matrix Format Tangential Interpolation
(MFTI) scheme described in reference [1] of the `$(@__MODULE__)` module documentation.

## Input Arguments:
- `L`, `σL`: The Loewner matrix (LM) and shifted LM for MFTI.  Each is a square matrix of order `n * p`,
  whose elements are defined in Eq. (9) of [1].
- `B`, `C`: The remaining matrices needed for the (unreduced) state representation in Eq. (8) of [1].
- `F`: A `LinearAlgebra.SVD` object as returned by `LinearAlgebra.svd` for the matrix pencil `s*L - σL`,
  for a particular choice of complex frequency `s`.
- `r`: A positive integer denoting the order of the reduced network.

## Return Values
- `Er`, `Ar`, `Br`, `Cr`: The matrices defining the reduced-order system, as defined in Eqs. (17) of [1],
  taking into account that Eq. (16) is erroneous; its RHS should read YΣXᴴ.
"""
function loewner_reduce(L, σL, B, C, F, r)
    Xr = @view F.V[:, 1:r] # n*p × r
    Yr = @view F.U[:, 1:r] # n*p × r
    Er = -(Yr' * L * Xr)
    Ar = -(Yr' * σL * Xr)
    Br = Yr' * B
    Cr = C * Xr
    return Er, Ar, Br, Cr
end

"""
    eval_reduced_model!(H, M, X, E, A, B, C, s) -> H
Evaluate the reduced-order Loewner model of the Matrix Format Tangential Interpolation
(MFTI) scheme, using Eq. (18) in reference [1] of the `$(@__MODULE__)` module documentation.

## Input Arguments:
- `H`: Complex square matrix with `size(H) == (p, p)` which will be overwritten
  with the function return value.
- `M`: Complex square storage matrix with `size(M) == (r, r) == size(E) == size(A)` which will be overwritten.
- `X`: Complex storage matrix with `size(X) = (r, p)` which will be overwritten.
- `E`, `A`: Two of the four reduced-order system matrices, as defined in Eqs. (17) of [1].
  `size(E) == size(A) == (r,r)`.
- `B`, `C`: The remaining two matrices defining the reduced-order system, as defined in Eqs. (17) of [1].
  `size(B) == (r, p)` and `size(C) == (p, r)`.
- `s`: Complex frequency `complex(0, 2π * f)` (with `f` in Hz) at which the transfer function matrix
  is to be interpolated.

## Return Values
- `H`: The input argument `H`, overwritten with the new interpolated tranfer function values at complex frequency `s`.

"""
function eval_reduced_model!(H, M, X, E, A, B, C, s)
    M .= @. s * E - A
    F = lu!(M)
    ldiv!(X, F, B)
    mul!(H, C, X)
    return H
end


"""
    loewner_pseudo_errors!(errors, f, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, Δf, sweep_options)
Compute pseudo errors using Eq. (20) in reference [1] of the `$(@__MODULE__)` module documentation, using a
sequential (i.e. non-threaded) or parallel (i.e. threaded) algorithm.

### Input Arguments
- `errors`: A floating point vector which will be overwritten with pseudo error vaLues, corresponding to to frequencies in `fgrid`.
  Errors for frequencies present in `f₀` will be set to negative infinity.
- `fgrid`: A vector of (real) frequencies at which the pseudo error is to be computed. `length(fgrid) == length(errors)`.
- `f₀`: A collection of (real) frequencies that have already been analyzed. Entries in `errors` corresponding to these
  frequencies will be set to negative infinity.
- `E_r1`, `A_r1`, `B_r1`, `C_r1`:  System matrices for the first reduced model used in the pseudo error calculation.
- `E_r2`, `A_r2`, `B_r2`, `C_r2`: System matrices for the second reduced model used in the pseudo error calculation.  Note
  that these may be equal to their corresponding members in the first model.
- `Δf`: Frequency perturbation.  A small value used to ensure that evaluation of the second model at perturbed frequencies
  will generate a distinct result compared to the first model.
- `sweep_options`: A struct or named tuple having at least the field
  * `parallel`: `true` to request parallel evaluation or `false` otherwise.  If `parallel == true` then `sweep_options` must
    also contain the following field:
  * `nthreads`: A positive integer denoting the number of tasks to launch for the parallel evaluation of all the frequencies in
    `fgrid`.
"""
function loewner_pseudo_errors!(errors, f, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, Δf, sweep_options)
    if sweep_options.parallel == false
        return loewner_pseudo_errors_sequential!(errors, f, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, Δf)
    else
        return loewner_pseudo_errors_parallel!(errors, f, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, Δf, sweep_options.nthreads)
    end
end

"""
    loewner_pseudo_errors_sequential!(errors, fgrid, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, options)
Compute pseudo errors using Eq. (20) in reference [1] of the `$(@__MODULE__)` module documentation, using a
sequential (i.e. non-threaded) algorithm.

### Input Arguments
- `errors`: A floating point vector which will be overwritten with pseudo error vaLues, corresponding to to frequencies in `fgrid`.
  Errors for frequencies present in `f₀` will be set to negative infinity.
- `fgrid`: A vector of (real) frequencies at which the pseudo error is to be computed. `length(fgrid) == length(errors)`.
- `f₀`: A collection of (real) frequencies that have already been analyzed. Entries in `errors` corresponding to these
  frequencies will be set to negative infinity.
- `E_r1`, `A_r1`, `B_r1`, `C_r1`:  System matrices for the first reduced model used in the pseudo error calculation.
- `E_r2`, `A_r2`, `B_r2`, `C_r2`: System matrices for the second reduced model used in the pseudo error calculation.  Note
  that these may be equal to their corresponding members in the first model.
- `options`: A `SweepOptions` instance providing options `random` and `Δf`.
"""
function loewner_pseudo_errors_sequential!(errors, fgrid, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, Δf)
    p  = size(C_r1, 1)
    r1 = size(E_r1, 1)
    r2 = size(E_r2, 1)

    M1 = Matrix{ComplexF64}(undef, r1, r1)
    M2 = Matrix{ComplexF64}(undef, r2, r2)

    X1 = Matrix{ComplexF64}(undef, r1, p)
    X2 = Matrix{ComplexF64}(undef, r2, p)

    H1 = Matrix{ComplexF64}(undef, p, p)
    H2 = Matrix{ComplexF64}(undef, p, p)
    ΔH = Matrix{ComplexF64}(undef, p, p)

    f₀_set = Set(f₀)
    for idx in eachindex(fgrid)
        fi = fgrid[idx]
        if fi in f₀_set
            errors[idx] = -Inf
            continue
        end
        s1 = 2π * im * fi
        s2 = 2π * im * (fi + Δf)

        eval_reduced_model!(H1, M1, X1, E_r1, A_r1, B_r1, C_r1, s1)
        eval_reduced_model!(H2, M2, X2, E_r2, A_r2, B_r2, C_r2, s2)
        @. ΔH = H2 - H1
        denom = maximum(svdvals!(H1))
        errors[idx] = denom == 0 ? Inf : maximum(svdvals!(ΔH)) / denom
    end

    return errors
end

"""
    loewner_pseudo_errors_parallel!(errors, fgrid, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, options)
Compute pseudo errors using Eq. (20) in reference [1] of the `$(@__MODULE__)` module documentation, using a
parallel (i.e. threaded) algorithm.

### Input Arguments
- `errors`: A floating point vector which will be overwritten with pseudo error vaLues, corresponding to to frequencies in `fgrid`.
  Errors for frequencies present in `f₀` will be set to negative infinity.
- `fgrid`: A vector of (real) frequencies at which the pseudo error is to be computed. `length(fgrid) == length(errors)`.
- `f₀`: A collection of (real) frequencies that have already been analyzed. Entries in `errors` corresponding to these
  frequencies will be set to negative infinity.
- `E_r1`, `A_r1`, `B_r1`, `C_r1`:  System matrices for the first reduced model used in the pseudo error calculation.
- `E_r2`, `A_r2`, `B_r2`, `C_r2`: System matrices for the second reduced model used in the pseudo error calculation.  Note
  that these may be equal to their corresponding members in the first model.
- `options`: A `SweepOptions` instance providing option `nthreads`.
"""
function loewner_pseudo_errors_parallel!(errors, fgrid, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, Δf, nthreads)
    p  = size(C_r1, 1)
    r1 = size(E_r1, 1)
    r2 = size(E_r2, 1)
    f₀_set = Set(f₀)
    n = length(fgrid)
    chunk_size = ceil(Int, n / nthreads)

    tasks = map(1:nthreads) do t
        Threads.@spawn begin
            M1 = Matrix{ComplexF64}(undef, r1, r1)
            M2 = Matrix{ComplexF64}(undef, r2, r2)
            X1 = Matrix{ComplexF64}(undef, r1, p)
            X2 = Matrix{ComplexF64}(undef, r2, p)
            H1 = Matrix{ComplexF64}(undef, p, p)
            H2 = Matrix{ComplexF64}(undef, p, p)
            ΔH = Matrix{ComplexF64}(undef, p, p)

            chunk = (t-1)*chunk_size+1 : min(t*chunk_size, n)
            for idx in chunk
                fi = fgrid[idx]
                if fi ∈ f₀_set
                    errors[idx] = -Inf
                    continue
                end
                s1 = 2*π * im * fi
                s2 = 2*π * im * (fi + Δf)
                eval_reduced_model!(H1, M1, X1, E_r1, A_r1, B_r1, C_r1, s1)
                eval_reduced_model!(H2, M2, X2, E_r2, A_r2, B_r2, C_r2, s2)
                @. ΔH = H2 - H1
                denom = maximum(svdvals(H1))
                errors[idx] = denom == 0 ? Inf : maximum(svdvals(ΔH)) / denom
            end
        end
    end
    foreach(wait, tasks)
    return errors
end


"""
    sweep(solve::Func, f, sweep_options) where Func -> lsm::LoewnerStateModel
Perform a fast frequency sweep.

## Input Arguments
- `solve`: A function (or callable object) that takes the (real) frequency as its only argument, and
  returns the `p × p` true scattering matrix evaluated at that frequency.
- `f`: A vector of frequencies at which the scattering matrix should be interpolated via fast sweep.
- `sweep_options`: A `SweepOptions` instance defining the type of sweep options to be enforced.

## Return Value
- `lsm`: A `LoewnerStateModel` instance with fields `E`, `A`, `B`, `C`, `d` updated to values that satisfy
  the convergence criterion encoded in `sweep_options`, and fields `f₀` and `H₀` updated to contain the
  values corresponding to all fully solved frequencies.
"""
function sweep(solve::Func, f, sweep_options) where Func

    d_flag = sweep_options.use_D
    p_flag = sweep_options.data_partition
    D = ones(sweep_options.p, sweep_options.p)

    fmin = minimum(f)
    fmax = maximum(f)
    n₀ = semi_adaptive_n(sweep_options, fmax)
    f₀ = Float64[]
    if sweep_options.adaptive
        append!(f₀, [fmin, fmax])
    else # semi-adaptive
        append!(f₀, semi_adaptive_freqs(fmin, fmax, max(2, n₀)))
    end

    H₀ = [solve(fᵢ) for fᵢ in f₀]
    if d_flag
        for Hᵢ in H₀
            Hᵢ .-= D
        end
    end

    sa, sb, Ha, Hb = loewner_data_partition(f₀, H₀, p_flag)
    L, σL = loewner_mfti(Ha, Hb, sa, sb)
    V, W = vw_mfti(Ha, Hb)

    errors = Vector{Float64}(undef, length(f))
    memory = 0
    while memory < sweep_options.memory
        x = 2π * (f₀[1] + f₀[end]) / 3
        F = svd_matrix_pencil(x, L, σL)
        r1 = loewner_order(F.S, sweep_options.q1)
        E_r1, A_r1, B_r1, C_r1 = loewner_reduce(L, σL, V, W, F, r1)
        r2 = loewner_order(F.S, min(sweep_options.q1 + 4, 12))
        E_r2, A_r2, B_r2, C_r2 = loewner_reduce(L, σL, V, W, F, r2)

        loewner_pseudo_errors!(errors, f, f₀, E_r1, A_r1, B_r1, C_r1, E_r2, A_r2, B_r2, C_r2, sweep_options.Δf, sweep_options)
        f_new = f[argmax(errors)]

        H_new = solve(f_new)
        if d_flag
            H_new .-= D
        end

        s_new = im * 2 * π * f_new
        Hr_new = C_r1 * ((s_new * E_r1 - A_r1) \ B_r1) #+ D
        error_act = maximum(svdvals(Hr_new - H_new)) / maximum(svdvals(H_new))
        if error_act <= sweep_options.tol
            memory += 1
        else
            memory = 0
        end
        push!(f₀, f_new)
        push!(H₀, H_new)
        sort_idx = sortperm(f₀)
        permute!(f₀, sort_idx)
        permute!(H₀, sort_idx)
        sa, sb, Ha, Hb = loewner_data_partition(f₀, H₀, p_flag)
        L, σL = loewner_mfti(Ha, Hb, sa, sb)
        V, W = vw_mfti(Ha, Hb)
    end

    x = im * 2π * (f₀[1] + f₀[end]) / 3
    F = svd_matrix_pencil(x, L, σL)
    r1 = loewner_order(F.S, sweep_options.q1)
    E_r1, A_r1, B_r1, C_r1 = loewner_reduce(L, σL, V, W, F, r1)

    return LoewnerStateModel(E_r1, A_r1, B_r1, C_r1, f₀, H₀)
end
